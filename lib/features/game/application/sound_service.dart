import 'package:audioplayers/audioplayers.dart';
import 'package:flutter/foundation.dart';

enum GameSound { correct, pass, tick, count, go, roundEnd, win }

/// Plays short sound effects. Failures are swallowed: sound must never break
/// or delay gameplay.
abstract interface class SoundService {
  Future<void> preload();
  void play(GameSound sound);
}

class SilentSoundService implements SoundService {
  const SilentSoundService();

  @override
  Future<void> preload() async {}

  @override
  void play(GameSound sound) {}
}

/// [SoundService] backed by low-latency `audioplayers` pools
/// (assets/sounds/*.wav, generated by tool/gen_sounds.py).
class AudioPoolSoundService implements SoundService {
  static const _files = {
    GameSound.correct: 'sounds/correct.wav',
    GameSound.pass: 'sounds/pass.wav',
    GameSound.tick: 'sounds/tick.wav',
    GameSound.count: 'sounds/count.wav',
    GameSound.go: 'sounds/go.wav',
    GameSound.roundEnd: 'sounds/round_end.wav',
    GameSound.win: 'sounds/win.wav',
  };

  final Map<GameSound, AudioPool> _pools = {};
  Future<void>? _loading;

  @override
  Future<void> preload() => _loading ??= _load();

  Future<void> _load() async {
    try {
      // Mix with whatever music is playing at the party instead of pausing it.
      await AudioPlayer.global.setAudioContext(
        AudioContextConfig(focus: AudioContextConfigFocus.mixWithOthers)
            .build(),
      );
    } catch (e) {
      debugPrint('audio context: $e');
    }
    for (final e in _files.entries) {
      try {
        _pools[e.key] = await AudioPool.createFromAsset(
          path: e.value,
          maxPlayers: 3,
          playerMode: PlayerMode.lowLatency,
        );
      } catch (err) {
        debugPrint('sound ${e.key}: $err');
      }
    }
  }

  @override
  void play(GameSound sound) {
    final pool = _pools[sound];
    if (pool == null) {
      preload();
      return;
    }
    pool.start().catchError((Object e) {
      debugPrint('play $sound: $e');
      return () async {};
    });
  }
}
