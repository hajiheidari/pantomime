def norm(s: str) -> str:
    s = s.replace("ي", "ی").replace("ى", "ی").replace("ك", "ک").replace("ـ", "")
    s = re.sub("[ً-ٰٟ]", "", s)
    return re.sub(r"\s+", "", s.replace("‌", "")).lower()


def main() -> None:
    path = pathlib.Path(__file__).resolve().parent.parent / "assets/words/words_fa.json"
    data = json.loads(path.read_text())
    # Words already used anywhere (avoid the same word in two categories too).
    used = {norm(w) for c in data["categories"] for lv in c["words"].values() for w in lv}
    added = skipped = 0
    by_id = {c["id"]: c for c in data["categories"]}
    for cid, levels in ADD.items():
        cat = by_id[cid]
        for level, words in levels.items():
            for w in words:
                w = w.strip()
                if not w:
                    continue
                k = norm(w)
                if k in used:
                    skipped += 1
                    continue
                used.add(k)
                cat["words"][level].append(w)
                added += 1
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    total = sum(len(lv) for c in data["categories"] for lv in c["words"].values())
    print(f"added {added}, skipped {skipped} duplicates, total {total}")


if __name__ == "__main__":
    main()
