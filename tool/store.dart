// Selects which ad-network packages are compiled into the app for a store.
//
//   dart run tool/store.dart <dev|play|bazaar|myket|ios> [--with-tapsell]
//   flutter pub get
//
// Flutter cannot exclude a plugin per Android flavor, so each store build
// gets its own dependency set: Bazaar/Myket builds must never contain AdMob
// or Google Play Services. This rewrites the managed block in pubspec.yaml
// and lib/features/ads/generated/ad_providers.g.dart. `dev` (committed
// default) = Adivery + AdMob so `flutter run` works on Android and iOS;
// packages/ads_tapsell is analyzed on its own (see docs/ads.md).
import 'dart:io';

const _packages = {
  'adivery': ('ads_adivery', 'AdiveryProvider'),
  'tapsell': ('ads_tapsell', 'TapsellProvider'),
  'admob': ('ads_admob', 'AdmobProvider'),
};

/// Tapsell is opt-in and currently NOT buildable: tapsell_plus 2.3.2 uses
/// jcenter() (removed in Gradle 9) and pins google_mobile_ads ^4.0.0 (also
/// unbuildable with AGP 9), and pulls Google Play Services. See docs/ads.md.
List<String> _profile(String store, bool withTapsell) => switch (store) {
  'dev' => ['adivery', if (withTapsell) 'tapsell', 'admob'],
  'play' => ['adivery', if (withTapsell) 'tapsell', 'admob'],
  'bazaar' || 'myket' || 'direct' => ['adivery', if (withTapsell) 'tapsell'],
  'ios' => ['admob'],
  'web' => [], // no ad SDKs in the browser yet (docs/web.md)
  _ => throw ArgumentError('unknown store "$store"'),
};

const _begin =
    '  # >>> ad providers (managed by tool/store.dart — do not edit)';
const _end = '  # <<< ad providers';

void main(List<String> args) {
  final positional = args.where((a) => !a.startsWith('--')).toList();
  if (positional.length != 1) {
    stderr.writeln(
      'usage: dart run tool/store.dart <dev|play|bazaar|myket|direct|ios|web> '
      '[--with-tapsell]',
    );
    exit(64);
  }
  final store = positional.single;
  final withTapsell = args.contains('--with-tapsell');
  final providers = _profile(store, withTapsell);

  // pubspec.yaml
  final pubspec = File('pubspec.yaml');
  final text = pubspec.readAsStringSync();
  final start = text.indexOf(_begin);
  final end = text.indexOf(_end);
  if (start < 0 || end < start) {
    stderr.writeln('managed block not found in pubspec.yaml');
    exit(1);
  }
  // Only ads_* packages may live in the managed block (it is rewritten).
  final existing = text.substring(start, end);
  final foreign = RegExp(r'^  ([a-z_]+):', multiLine: true)
      .allMatches(existing)
      .map((m) => m.group(1)!)
      .where((name) => !name.startsWith('ads_'))
      .toList();
  if (foreign.isNotEmpty) {
    stderr.writeln(
      'pubspec.yaml: move ${foreign.join(', ')} out of the ad providers '
      'block (above "# >>>" or below "# <<<") and run again.',
    );
    exit(1);
  }
  final block = StringBuffer('$_begin\n')
    ..writeln('  # store: $store')
    ..writeln('  ads_core:')
    ..writeln('    path: packages/ads_core');
  for (final p in providers) {
    final pkg = _packages[p]!.$1;
    block
      ..writeln('  $pkg:')
      ..writeln('    path: packages/$pkg');
  }
  pubspec.writeAsStringSync(text.replaceRange(start, end, block.toString()));

  // Registry
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/store.dart — do not edit.')
    ..writeln('// Store profile: $store')
    ..writeln()
    ..writeln("import 'package:ads_core/ads_core.dart';");
  for (final p in providers) {
    final pkg = _packages[p]!.$1;
    out.writeln("import 'package:$pkg/$pkg.dart';");
  }
  out
    ..writeln()
    ..writeln("const adStoreProfile = '$store';")
    ..writeln()
    ..writeln('/// Ad networks compiled into this build.')
    ..writeln('Map<String, AdProvider Function()> compiledAdProviders() => {');
  for (final p in providers) {
    out.writeln("  '$p': ${_packages[p]!.$2}.new,");
  }
  out.writeln('};');
  File('lib/features/ads/generated/ad_providers.g.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());

  stdout.writeln('Store "$store": ${providers.join(', ')}.');
  if (providers.contains('admob') && !providers.contains('tapsell')) {
    // Without Tapsell nothing pins AdMob to 4.x; take the latest.
    stdout.writeln('Now run: flutter pub upgrade google_mobile_ads');
  } else {
    stdout.writeln('Now run: flutter pub get');
  }
}
